export type TKey = keyof typeof ar;
const DICTS: Record<Lang, Dict> = { ar, en };

type Ctx = {
  lang: Lang;
  rtl: boolean;
  t: (key: TKey) => string;
  /** label for a dynamic code ("st_", "rt_"…), falling back to the code itself */
  tc: (prefix: string, code: string | null | undefined) => string;
  setLang: (lang: Lang) => void;
};

const I18nContext = createContext<Ctx | null>(null);

export function I18nProvider({ children }: { children: React.ReactNode }) {
  const [lang, setLangState] = useState<Lang>(() => (getLocales()[0]?.languageCode === "en" ? "en" : "ar"));

  useEffect(() => {
    getItem("lang").then((saved) => saved && setLangState(saved === "en" ? "en" : "ar"));
  }, []);

  const setLang = useCallback((next: Lang) => {
    setLangState(next);
    setItem("lang", next);
  }, []);

  const value = useMemo<Ctx>(() => {
    const dict = DICTS[lang];
    return {
      lang,
      rtl: lang === "ar",
      t: (key) => dict[key] ?? key,
      tc: (prefix, code) => (code ? (dict as Record<string, string>)[prefix + code] ?? code : "—"),
      setLang,
    };
  }, [lang, setLang]);

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n() {
  const ctx = useContext(I18nContext);
  if (!ctx) throw new Error("useI18n outside I18nProvider");
  return ctx;
}
